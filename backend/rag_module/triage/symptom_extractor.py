
import json
from pathlib import Path

from gigachat import GigaChat
from gigachat.models import (
    ChatCompletionRequest,
    ChatMessage,
    ChatContentPart,
    ChatModelOptions,
    ChatResponseFormat,
)

from rag_module.config import (
    GIGACHAT_CREDENTIALS,
    GIGACHAT_SCOPE,
    GIGACHAT_MODEL,
)

from rag_module.triage.symptom_models import (
    SymptomExtraction,
    SYMPTOM_EXTRACTION_JSON_SCHEMA,
)


PROJECT_ROOT = Path(__file__).resolve().parents[2]
CERT_PATH = PROJECT_ROOT / "certs" / "russian_trusted_root_ca_pem.crt"


def extract_symptoms(answers: list[dict]) -> dict:
    """
    Извлекает симптомы и их контекст из ответов пользователя.

    Не использует RAG и Qdrant.
    Не ставит диагнозы и не определяет медицинскую безопасность.

    Возвращает структурированный словарь.
    """

    if not GIGACHAT_CREDENTIALS:
        raise RuntimeError(
            "Не указан GIGACHAT_CREDENTIALS в файле .env"
        )

    if not isinstance(answers, list) or not answers:
        raise ValueError(
            "Необходимо передать хотя бы один ответ пользователя."
        )

    answers_text = []

    for index, item in enumerate(answers, start=1):
        if not isinstance(item, dict):
            continue

        question = item.get("question")
        answer = item.get("answer")

        if not isinstance(answer, str) or not answer.strip():
            continue

        if isinstance(question, str) and question.strip():
            answers_text.append(
                f"Вопрос {index}: {question.strip()}\n"
                f"Ответ пользователя: {answer.strip()}"
            )
        else:
            answers_text.append(
                f"Ответ пользователя {index}: {answer.strip()}"
            )

    if not answers_text:
        raise ValueError(
            "Не найдено корректных ответов пользователя."
        )

    context = "\n\n".join(answers_text)

    prompt = f"""
Ты — компонент извлечения медицинских симптомов
из текста ответов пользователя.

Твоя задача — извлечь упомянутые симптомы и точно
передать контекст каждого симптома в заданной JSON-схеме.

ВАЖНО:
Ты не ставишь диагнозы, не оцениваешь вероятность
заболеваний и не определяешь, безопасно ли состояние.
Ты только извлекаешь информацию из текста.

ПРАВИЛА ИЗВЛЕЧЕНИЯ:

1. Извлекай все явно упомянутые симптомы и жалобы,
   включая симптомы, наличие которых пользователь отрицает.

2. Не пропускай симптом только потому, что он указан
   в отрицательной форме.

3. Каждый отдельно упомянутый симптом должен получить
   собственный объект в массиве symptoms.

4. Не придумывай симптомы, которых пользователь не упоминал.

5. Не заменяй конкретный симптом предположительным диагнозом.

6. status:
   - present — симптом присутствует;
   - absent — пользователь прямо отрицает симптом;
   - unclear — невозможно определить, присутствует ли симптом.

7. Сохраняй отрицание именно того симптома, к которому
   оно относится. Не распространяй отрицание на другие
   симптомы в предложении.
8. Фразы "не могу дышать" и "не хватает воздуха"
   описывают присутствующий симптом, а не его отрицание.
9. Если пользователь сообщает о нескольких симптомах,
   создай отдельный объект для каждого.
10. Если симптом был раньше, не обозначай его как текущий,
    если пользователь не сообщил, что он продолжается.
11. Если пользователь говорит о другом человеке,
    не приписывай его симптомы самому пользователю.
12. Если пользователь прямо сомневается в наличии симптома,
    установи status="unclear" для этого симптома.
13. Если невозможно определить, присутствует ли симптом,
    не выбирай status="present" или status="absent" без оснований.
14. Если формулировка неоднозначна или пользователь
    сомневается в наличии симптома, установи uncertainty=true.
15. Если все упомянутые симптомы понятны и их контекст
    определён, установи uncertainty=false.
16. Не делай вывод о том, что отсутствие упоминания
    симптома означает его отсутствие.
17. Не объединяй разные симптомы в один, если это
    меняет смысл исходного сообщения.
18. Не добавляй информацию, которой нет в ответах пользователя.
19. Сохраняй различия между текущими и прошлыми симптомами.
20. Учитывай отрицания, сомнения и упоминания других людей
    во всём контексте ответов, а не только в последнем ответе.
21. Разделяй время возникновения симптома и его наличие.
    status отвечает на вопрос, присутствовал ли симптом
    в указанный период.
    time отвечает на вопрос, когда он присутствовал.

22. Если пользователь сообщает, что симптом был раньше,
    а сейчас прошёл, создай два объекта:
    - status="present", time="past";
    - status="absent", time="current".

23. Если пользователь прямо отрицает наличие симптома
    в определённый период, используй status="absent"
    и соответствующее значение time.

24. Не создавай два объекта, если пользователь просто
    сообщает о прошлом симптоме и не говорит,
    что сейчас он отсутствует.

24. Если пользователь не упоминает никаких симптомов
    или жалоб, верни пустой массив symptoms.

25. Если symptoms пустой и в ответах нет неоднозначных
    высказываний о симптомах, uncertainty должен быть false.

26. Само по себе отсутствие информации о симптомах
    не является неопределённостью.

27. Не путай отсутствие упоминания симптома
    с отрицанием симптома.

28. При перечислении нескольких симптомов извлекай каждый
    из них отдельно, даже если один симптом отрицается,
    а другой подтверждается.
29. uncertainty относится к неоднозначности извлечённой
    информации, а не к недостатку медицинских данных.

30. Если пользователь не сообщает симптомы, но и не
    выражает сомнений относительно какого-либо симптома,
    верни symptoms=[] и uncertainty=false.

31. Не устанавливай uncertainty=true только потому,
    что пользователь не ответил на медицинские вопросы
    или не предоставил достаточно информации.

32. Название симптома должно кратко и точно передавать
    сам симптом, упомянутый пользователем.

33. Не добавляй к названию симптома слова, описывающие
    мысли, предположения или размышления пользователя,
    если они не являются частью самого симптома.

34. Не заменяй название симптома случайным словом,
    которого нет в исходном сообщении и которое
    не является его корректным медицинским обозначением.

35. При отрицании сохраняй исходный симптом.
    Например:
    "не болит грудь" означает:
    name="боль в груди",
    status="absent",
    time="current".

36. Не изменяй название симптома из-за наличия
    отрицания перед ним.

37. Если пользователь говорит "мне тяжело дышать",
    допустимо использовать название "тяжело дышать"
    или "затрудненное дыхание".

38. Не добавляй симптомы, которые не упоминались
    в исходном тексте.

    
39. Для каждого симптома обязательно заполняй поле severity:
    - mild — если пациент явно указал лёгкую выраженность;
    - moderate — если явно указал умеренную выраженность;
    - severe — если явно указал сильную выраженность;
    - unknown — если выраженность не указана.

40. Поле onset содержит описание начала симптома.
    Сохраняй формулировку пациента, например:
    "сегодня утром", "вчера вечером", "три дня назад".
    Если начало неизвестно, возвращай null.

41. Поле frequency:
    - constant — если симптом постоянный;
    - intermittent — если симптом периодический;
    - single_episode — если пациент описал один отдельный эпизод;
    - unknown — если информации недостаточно.

42. Поле details содержит дополнительные характеристики,
    которые пациент явно сообщил.
    Не добавляй медицинские предположения.
    Если дополнительных характеристик нет, возвращай [].

43. Все новые поля должны присутствовать в JSON.
    Неизвестные значения заполняй согласно правилам выше.

44. Не определяй severity по опасности симптома.
    Например, головная боль сама по себе не означает severe.
    Используй только слова и описание пациента.

45. Не определяй single_episode только по тому,
что симптом упомянут один раз.

single_episode используй только при явном указании
на единичный эпизод:
"это произошло один раз",
"был только один приступ",
"однократный эпизод".

Частота симптома может иметь только три значения:

constant — пациент явно сообщает, что симптом постоянный.

intermittent — пациент явно сообщает, что симптом
периодически появляется и исчезает.

unknown — частота не указана или недостаточно информации.

Не определяй частоту по количеству упоминаний симптома.
Не используй single_episode.
Однократное упоминание симптома не означает,
что он возник только один раз.

46. Строго учитывай выраженность симптома:

"сильно болит", "очень сильная боль",
"резко выраженная боль" -> severe.

"умеренная боль", "терпимая боль" -> moderate.

"слабая боль", "незначительная боль" -> mild.

Не заменяй явно указанную выраженность
на другую категорию.

47. Если пациент сообщает, что симптом был раньше,
но сейчас прошёл, сохрани обе временные характеристики:

- отдельная запись: status=present, time=past;
- отдельная запись: status=absent, time=current.

Не теряй информацию о прошлом симптоме.

48. Не делай вывод о частоте симптома
по количеству его упоминаний в тексте.

ПРЕДЫДУЩИЕ ВОПРОСЫ И ОТВЕТЫ:

{context}

Верни только JSON согласно заданной схеме.
"""

    request = ChatCompletionRequest(
        model=GIGACHAT_MODEL,
        messages=[
            ChatMessage(
                role="user",
                content=[
                    ChatContentPart(text=prompt)
                ]
            )
        ],
        model_options=ChatModelOptions(
            response_format=ChatResponseFormat(
                type="json_schema",
                schema_=SYMPTOM_EXTRACTION_JSON_SCHEMA,
                strict=True,
            )
        )
    )

    with GigaChat(
        credentials=GIGACHAT_CREDENTIALS,
        scope=GIGACHAT_SCOPE,
        model=GIGACHAT_MODEL,
        ca_bundle_file=str(CERT_PATH)
    ) as client:

        response = client.chat.create(request)

    if not response.messages:
        raise RuntimeError(
            "GigaChat не вернул сообщение."
        )

    content = response.messages[0].content

    if not content or not content[0].text:
        raise RuntimeError(
            "GigaChat вернул пустой ответ."
        )

    try:
        data = json.loads(content[0].text.strip())

        payload = SymptomExtraction.model_validate(data)

    except json.JSONDecodeError as error:
        raise RuntimeError(
            f"GigaChat вернул некорректный JSON: {error}. "
            f"Ответ: {content[0].text!r}"
        ) from error

    except ValueError as error:
        raise RuntimeError(
            f"JSON не соответствует модели SymptomExtraction: {error}. "
            f"Ответ: {content[0].text!r}"
        ) from error

    return payload.model_dump()
